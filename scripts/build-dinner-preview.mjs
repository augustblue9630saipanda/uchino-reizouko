import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';

// Inline the same recipe renderer as the app. Local file opening needs no local JS imports.
const app=readFileSync(new URL('../index.html',import.meta.url),'utf8');
const renderer=app.slice(app.indexOf('function dinnerText('),app.indexOf("$('generateDinner').onclick="));
if(!renderer.includes('function renderDinner('))throw Error('Dinner renderer missing');
const template=readFileSync(new URL('../tests/dinner-preview.template.html',import.meta.url),'utf8');
writeFileSync(new URL('../dinner-test.html',import.meta.url),template.replace('/* INLINE_DINNER_RENDERER */',renderer));

// Dashboard editor can paste one file; preserve the modular sources as the source of truth.
const contract=readFileSync(new URL('../supabase/functions/generate-dinner/contract.mjs',import.meta.url),'utf8').replace(/^export /gm,'');
const handler=readFileSync(new URL('../supabase/functions/generate-dinner/handler.mjs',import.meta.url),'utf8').replace(/^import .*;\r?\n/gm,'').replace(/^export /gm,'');
mkdirSync(new URL('../supabase/dashboard/',import.meta.url),{recursive:true});
writeFileSync(new URL('../supabase/dashboard/generate-dinner-preview.ts',import.meta.url),
 '// GENERATED by node scripts/build-dinner-preview.mjs. TEST PROJECT ONLY.\n// @ts-nocheck\n'+contract+'\n'+handler+'\nDeno.serve(createDinnerHandler({env:(name:string)=>Deno.env.get(name),preview:true}));\n');
writeFileSync(new URL('../supabase/dashboard/generate-dinner.ts',import.meta.url),
 '// GENERATED by node scripts/build-dinner-preview.mjs. Registered household mode.\n// @ts-nocheck\n'+contract+'\n'+handler+'\nDeno.serve(createDinnerHandler({env:(name:string)=>Deno.env.get(name)}));\n');
